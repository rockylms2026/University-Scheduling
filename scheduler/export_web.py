"""The hosted version: the scheduling page backed by Supabase, with logins and roles.

  web/index.html           the page (static; host it on Vercel, Netlify, or GitHub Pages)
  supabase/seed.sql        faculty and classes of the semester, from the data files
  supabase/setup.sql       schema.sql + seed.sql + first admin;
                           paste it once into the Supabase SQL Editor
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

from .export_planner import TEMPLATE_PATH, planner_data, seal_data_url
from .model import University

ROOT = Path(__file__).resolve().parent.parent
WEB_DIR = ROOT / "web"
SUPABASE_DIR = ROOT / "supabase"
SUPABASE_JS = "https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.45.4/dist/umd/supabase.js"
CONFIG_PATH = SUPABASE_DIR / "config.json"


def q(v) -> str:
    """A SQL literal."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def seed_sql(uni: University, semester: int) -> str:
    data = planner_data(uni, semester)
    # Plain statements only: no begin and commit, no temporary or working tables. The Supabase SQL
    # Editor did not let later statements see a table or schema made earlier in the same run, so each
    # statement carries the lists it needs. Every statement is safe to run again.
    out = ["-- Faculty and classes, generated by: python -m scheduler web"]
    rows = [f"({q(k)}, {q(t['name'])}, {q(t['college'])}, {q(t['dept'])}, {q(t['rank'])}, {q(t['role'])}, {q(t['max'])}, {q(t['degree'] or None)}, {q(t['spec'] or None)})"
            for k, t in sorted(data["teachers"].items())]
    out.append("-- Specializations come from the loading plans, and one typed on the Faculty Profiles page is kept.\n"
               "insert into public.faculty (key, name, college, department, rank, designation, max_lu, degree, specialization) values\n  "
               + ",\n  ".join(rows) + "\non conflict (key) do update set name = excluded.name, college = excluded.college,"
               " department = excluded.department, rank = excluded.rank, designation = excluded.designation, max_lu = excluded.max_lu,"
               " degree = excluded.degree, specialization = coalesce(public.faculty.specialization, excluded.specialization);")
    keys = "(values " + ", ".join(f"({q(k)})" for k in sorted(data["teachers"])) + ") as s(key)"
    renames = (yaml.safe_load(RENAMES_PATH.read_text()) or {}).get("renames") or {} if RENAMES_PATH.exists() else {}
    moves = "(values " + ", ".join(f"({q(a)}, {q(b)})" for a, b in sorted(renames.items())) + ") as r(old_key, new_key)" if renames else None
    depts = "(values " + ", ".join(f"({q(d)}, {q(c)})" for d, c in sorted(data["deptCollege"].items())) + ") as d(department, college)"
    out.append(FACULTY_MIGRATION.replace("{keys}", keys).replace("{depts}", depts)
               .replace("{moves}", moves or "(select null::text as old_key, null::text as new_key where false) as r"))
    rows = []
    for c in data["classes"]:
        prog = data["programs"][data["sections"][c["section"]]["program"]]
        rows.append(f"({q(c['id'])}, {semester}, {q(c['course'])}, {q(c['section'])}, {q(data['sections'][c['section']]['program'])}, "
                    f"{q(prog['college'])}, {q(prog['dept'])}, {q(data['courses'][c['course']]['college'] == 'CORE')}, {q(c['teacher'])}, {q(c['house'])}, {q(c['houseCollege'])})")
    out.append("insert into public.classes (id, sem, course, section, program, college, department, is_ge, plan_teacher, house_dept, house_college) values\n  "
               + ",\n  ".join(rows) + "\non conflict (id) do update set course = excluded.course, section = excluded.section,"
               " program = excluded.program, college = excluded.college, department = excluded.department,"
               " is_ge = excluded.is_ge, plan_teacher = excluded.plan_teacher, house_dept = excluded.house_dept, house_college = excluded.house_college;")
    ids = "(values " + ", ".join(f"({q(c['id'])})" for c in data["classes"]) + ") as s(id)"
    out.append(CLASS_MIGRATION.replace("{sem}", str(semester)).replace("{ids}", ids))
    rows = [f"({q(code)}, {q(d)}, {q(data['deptCollege'][d])})" for code, depts in data["geTeachers"].items() for d in depts]
    out.append("-- Departments that may teach each GE course (kept as edited on the Settings page).\n"
               f"delete from public.ge_teachers where department not in (select department from {depts});\n"
               f"update public.ge_teachers t set college = d.college from {depts} where t.department = d.department;\n"
               "insert into public.ge_teachers (course, department, college) values\n  " + ",\n  ".join(rows)
               + "\non conflict (course, department) do nothing;")
    out.append("-- Working tables made by an earlier version of this script.\ndrop schema if exists seed cascade;")
    return "\n".join(out) + "\n"


# When the colleges were reorganized, faculty keys changed (data/faculty_key_renames.yaml): what the
# database holds under an old key moves to the new one. Every college code is set again from the
# department. Faculty no longer in the plans are removed, and so are the teachers chosen from them.
RENAMES_PATH = ROOT / "data" / "faculty_key_renames.yaml"
FACULTY_MIGRATION = """-- Faculty keys that changed: move typed specializations and chosen teachers to the new keys.
update public.faculty n set specialization = o.specialization from public.faculty o, {moves}
  where o.key = r.old_key and n.key = r.new_key and o.specialization is not null;
update public.classes c set plan_teacher = r.new_key from {moves} where c.plan_teacher = r.old_key;
update public.teacher_changes t set teacher = r.new_key from {moves} where t.teacher = r.old_key;
update public.ge_decisions t set teacher = r.new_key from {moves} where t.teacher = r.old_key;
-- College codes follow the departments.
update public.staff s set college = d.college from {depts} where s.role = 'chair' and s.department = d.department;
update public.staff set college = case college when 'CSS' then 'CSBS' when 'CICS' then 'CILS' when 'CISC' then 'CILS'
  when 'CBE' then 'CBAPA' else college end where role = 'associate_dean';
update public.ge_requests t set college = d.college from {depts} where t.department = d.department;
update public.instructor_requests t set college = d.college from {depts} where t.department = d.department;
update public.submissions t set college = d.college from {depts} where t.department = d.department;
-- Faculty no longer in the plans: clear the classes given to them, then remove them.
update public.classes set plan_teacher = null where plan_teacher is not null and plan_teacher not in (select key from {keys});
delete from public.teacher_changes where teacher is not null and teacher not in (select key from {keys});
update public.ge_decisions set teacher = null where teacher is not null and teacher not in (select key from {keys});
delete from public.faculty where key not in (select key from {keys});"""

# Class ids are now made from the course and the section (S1-PSYC101-BSP1A). Bookings, teachers and
# requests made under an older id move to the class with the same course and section. Programs that
# now run one section a year keep what was booked for their Section A. BS Psychology Years 3 and 4 were
# sections C and IO and are now A and B with track groups 3-C and 3-IO: track courses go to the group,
# common courses of C to A and of IO to B.
# Classes that no longer exist are removed with what was booked for them.
CLASS_MIGRATION = """-- Move what was booked under older class ids to the same course and section.
with keep as (select id from {ids}),
  m as (select o.id as old_id, n.id as new_id from public.classes o
    join public.classes n on n.sem = o.sem and n.course = o.course
     and (n.section = o.section
       or (o.section ~ '^(ABC|ABEcon|BLIS|BSEntrep) [1-4]A$' and n.section = left(o.section, -1))
       or (o.section ~ '^BSP [34]C$' and n.section in (left(o.section, 5) || '-C', left(o.section, 5) || 'A'))
       or (o.section ~ '^BSP [34]IO$' and n.section in (left(o.section, 5) || '-IO', left(o.section, 5) || 'B')))
    where o.sem = {sem} and o.id not in (select id from keep) and n.id in (select id from keep)),
  b as (update public.bookings b set class_id = m.new_id from m
    where b.class_id = m.old_id and not exists (select 1 from public.bookings x where x.class_id = m.new_id and x.part = b.part) returning 1),
  t as (update public.teacher_changes t set class_id = m.new_id from m
    where t.class_id = m.old_id and not exists (select 1 from public.teacher_changes x where x.class_id = m.new_id) returning 1),
  r as (update public.ge_requests t set class_id = m.new_id from m
    where t.class_id = m.old_id and not exists (select 1 from public.ge_requests x where x.class_id = m.new_id) returning 1),
  d as (update public.ge_decisions t set class_id = m.new_id from m
    where t.class_id = m.old_id and not exists (select 1 from public.ge_decisions x where x.class_id = m.new_id) returning 1),
  i as (update public.instructor_requests t set class_id = m.new_id from m
    where t.class_id = m.old_id and not exists (select 1 from public.instructor_requests x where x.class_id = m.new_id) returning 1)
select (select count(*) from b) as bookings_moved, (select count(*) from t) as teachers_moved,
  (select count(*) from r) + (select count(*) from d) + (select count(*) from i) as requests_moved;
-- Classes no longer in the curricula go, with whatever was booked for them.
delete from public.classes where sem = {sem} and id not in (select id from {ids});"""


# Requests are made by the chairs, to departments that have submitted. Earlier versions of this setup
# sent requests by themselves; take those back.
DEFAULT_REQUESTS = """-- Remove requests that an earlier setup sent by itself (chairs now ask instructors of submitted departments).
delete from public.ge_decisions where class_id in (select class_id from public.ge_requests where requested_by = 'setup');
delete from public.ge_requests where requested_by = 'setup';
"""


def build_label() -> str:
    """Date of the build, e.g. "Oct 12, 07:40", so people can tell which version they have open."""
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).strftime("%b %d, %H:%M UTC")


def write_web(uni: University, semester: int = 1) -> list[Path]:
    cfg = json.loads(CONFIG_PATH.read_text())
    SUPABASE_DIR.mkdir(exist_ok=True)
    seed = seed_sql(uni, semester)
    (SUPABASE_DIR / "seed.sql").write_text(seed)
    admin = cfg.get("first_admin")
    first = (f"-- The first account with full access (the Registrar). Add everyone else on the Settings page.\n"
             f"insert into public.staff (email, full_name, role) values ({q(admin['email'].lower())}, {q(admin.get('name', ''))}, 'registrar')\n"
             "on conflict (email) do nothing;\n") if admin else ""
    setup = "\n".join(["-- Class Scheduling: run this once in the Supabase SQL Editor (it is safe to run again).",
                       (SUPABASE_DIR / "schema.sql").read_text(), seed, first, DEFAULT_REQUESTS])
    (SUPABASE_DIR / "setup.sql").write_text(setup)

    data = json.dumps(planner_data(uni, semester), separators=(",", ":")).replace("</", "<\\/")
    backend = json.dumps({"kind": "supabase", "url": cfg["url"], "key": cfg["anon_key"]})
    html = (TEMPLATE_PATH.read_text()
            .replace("/*__DATA__*/null", data)
            .replace('/*__SEAL__*/""', json.dumps(seal_data_url()))
            .replace("/*__BACKEND__*/null", backend)
            .replace('/*__BUILD__*/""', json.dumps(build_label()))
            .replace("<!--__SUPABASE_JS__-->", f'<script src="{SUPABASE_JS}"></script>'))
    WEB_DIR.mkdir(exist_ok=True)
    (WEB_DIR / "index.html").write_text(html)
    return [WEB_DIR / "index.html", SUPABASE_DIR / "seed.sql", SUPABASE_DIR / "setup.sql"]
