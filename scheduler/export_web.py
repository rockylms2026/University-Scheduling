"""The hosted version: the scheduling page backed by Supabase, with logins and roles.

  web/index.html           the page (static; host it on Vercel, Netlify, or GitHub Pages)
  supabase/seed.sql        faculty and classes of the semester, from the data files
  supabase/setup.sql       schema.sql + seed.sql + first admin;
                           paste it once into the Supabase SQL Editor
"""

from __future__ import annotations

import json
from pathlib import Path

from .export_planner import TEMPLATE_PATH, planner_data, seal_data_url
from .model import University

ROOT = Path(__file__).resolve().parent.parent
WEB_DIR = ROOT / "web"
SUPABASE_DIR = ROOT / "supabase"
SUPABASE_JS = "https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.45.4/dist/umd/supabase.js"
CONFIG_PATH = SUPABASE_DIR / "config.json"


def q(v) -> str:
    """A SQL literal."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def seed_sql(uni: University, semester: int) -> str:
    data = planner_data(uni, semester)
    out = ["-- Faculty and classes, generated by: python -m scheduler web", "begin;"]
    rows = [f"({q(k)}, {q(t['name'])}, {q(t['college'])}, {q(t['dept'])}, {q(t['rank'])}, {q(t['role'])}, {q(t['max'])}, {q(t['degree'] or None)}, {q(t['spec'] or None)})"
            for k, t in sorted(data["teachers"].items())]
    out.append("create temp table seed_faculty (key text primary key, name text, college text, department text, rank text,"
               " designation text, max_lu int, degree text, specialization text) on commit drop;\n"
               "insert into seed_faculty values\n  " + ",\n  ".join(rows) + ";")
    out.append("-- Specializations come from the loading plans, and one typed on the Faculty Profiles page is kept.\n"
               "insert into public.faculty (key, name, college, department, rank, designation, max_lu, degree, specialization)\n"
               "select key, name, college, department, rank, designation, max_lu, degree, specialization from seed_faculty\n"
               "on conflict (key) do update set name = excluded.name, college = excluded.college,"
               " department = excluded.department, rank = excluded.rank, designation = excluded.designation, max_lu = excluded.max_lu,"
               " degree = excluded.degree, specialization = coalesce(public.faculty.specialization, excluded.specialization);")
    out.append(FACULTY_MIGRATION)
    rows = []
    for c in data["classes"]:
        prog = data["programs"][data["sections"][c["section"]]["program"]]
        rows.append(f"({q(c['id'])}, {semester}, {q(c['course'])}, {q(c['section'])}, {q(data['sections'][c['section']]['program'])}, "
                    f"{q(prog['college'])}, {q(prog['dept'])}, {q(data['courses'][c['course']]['college'] == 'CORE')}, {q(c['teacher'])}, {q(c['house'])}, {q(c['houseCollege'])})")
    out.append("create temp table seed_classes (id text primary key, sem int, course text, section text, program text, college text,"
               " department text, is_ge boolean, plan_teacher text, house_dept text, house_college text) on commit drop;\n"
               "insert into seed_classes values\n  " + ",\n  ".join(rows) + ";")
    out.append("insert into public.classes (id, sem, course, section, program, college, department, is_ge, plan_teacher, house_dept, house_college)\n"
               "select id, sem, course, section, program, college, department, is_ge, plan_teacher, house_dept, house_college from seed_classes\n"
               "on conflict (id) do update set course = excluded.course, section = excluded.section,"
               " program = excluded.program, college = excluded.college, department = excluded.department,"
               " is_ge = excluded.is_ge, plan_teacher = excluded.plan_teacher, house_dept = excluded.house_dept, house_college = excluded.house_college;")
    out.append(CLASS_MIGRATION.replace("{sem}", str(semester)))
    rows = [f"({q(code)}, {q(d)}, {q(data['deptCollege'][d])})" for code, depts in data["geTeachers"].items() for d in depts]
    out.append("-- Departments that may teach each GE course (kept as edited on the Settings page).\n"
               "update public.ge_teachers set college = 'CICS' where college = 'CISC';\n"
               "insert into public.ge_teachers (course, department, college) values\n  " + ",\n  ".join(rows)
               + "\non conflict (course, department) do nothing;")
    out.append("commit;")
    return "\n".join(out) + "\n"


# The College of Information and Computing Sciences was called CISC in earlier data: its faculty keys
# change from CISC-.. to CICS-.. (typed specializations and chosen teachers move along). Faculty no
# longer in the plans are removed, and so are the teachers chosen from them.
FACULTY_MIGRATION = """-- CISC is now CICS. Move what points at the old faculty keys to the new ones.
update public.faculty n set specialization = o.specialization from public.faculty o
  where o.key like 'CISC-%' and n.key = 'CICS-' || substr(o.key, 6) and o.specialization is not null;
update public.classes set plan_teacher = 'CICS-' || substr(plan_teacher, 6) where plan_teacher like 'CISC-%';
update public.teacher_changes set teacher = 'CICS-' || substr(teacher, 6) where teacher like 'CISC-%';
update public.ge_decisions set teacher = 'CICS-' || substr(teacher, 6) where teacher like 'CISC-%';
update public.staff set college = 'CICS' where college = 'CISC';
update public.ge_requests set college = 'CICS' where college = 'CISC';
update public.instructor_requests set college = 'CICS' where college = 'CISC';
update public.submissions set college = 'CICS' where college = 'CISC';
-- Faculty no longer in the plans: clear the classes given to them, then remove them.
update public.classes set plan_teacher = null where plan_teacher is not null and plan_teacher not in (select key from seed_faculty);
delete from public.teacher_changes where teacher is not null and teacher not in (select key from seed_faculty);
update public.ge_decisions set teacher = null where teacher is not null and teacher not in (select key from seed_faculty);
delete from public.faculty where key not in (select key from seed_faculty);"""

# Class ids are now made from the course and the section (S1-PSYC101-BSP1A). Bookings, teachers and
# requests made under an older id move to the class with the same course and section. Programs that
# now run one section a year (ABC, ABEcon, BLIS, BSEntrep) keep what was booked for their Section A.
# Classes that no longer exist are removed with what was booked for them.
CLASS_MIGRATION = """-- Move what was booked under older class ids to the same course and section.
create temp table class_moves on commit drop as
  select o.id as old_id, n.id as new_id from public.classes o
  join seed_classes n on n.sem = o.sem and n.course = o.course
   and (n.section = o.section or (o.section ~ '^(ABC|ABEcon|BLIS|BSEntrep) [1-4]A$' and n.section = left(o.section, -1)))
  where o.sem = {sem} and o.id not in (select id from seed_classes);
update public.bookings b set class_id = m.new_id from class_moves m
  where b.class_id = m.old_id and not exists (select 1 from public.bookings x where x.class_id = m.new_id and x.part = b.part);
update public.teacher_changes t set class_id = m.new_id from class_moves m
  where t.class_id = m.old_id and not exists (select 1 from public.teacher_changes x where x.class_id = m.new_id);
update public.ge_requests t set class_id = m.new_id from class_moves m
  where t.class_id = m.old_id and not exists (select 1 from public.ge_requests x where x.class_id = m.new_id);
update public.ge_decisions t set class_id = m.new_id from class_moves m
  where t.class_id = m.old_id and not exists (select 1 from public.ge_decisions x where x.class_id = m.new_id);
update public.instructor_requests t set class_id = m.new_id from class_moves m
  where t.class_id = m.old_id and not exists (select 1 from public.instructor_requests x where x.class_id = m.new_id);
-- Classes no longer in the curricula go, with whatever was booked for them.
delete from public.classes where sem = {sem} and id not in (select id from seed_classes);"""


# Requests are made by the chairs, to departments that have submitted. Earlier versions of this setup
# sent requests by themselves; take those back.
DEFAULT_REQUESTS = """-- Remove requests that an earlier setup sent by itself (chairs now ask instructors of submitted departments).
delete from public.ge_decisions where class_id in (select class_id from public.ge_requests where requested_by = 'setup');
delete from public.ge_requests where requested_by = 'setup';
"""


def build_label() -> str:
    """Date of the build, e.g. "Oct 12, 07:40", so people can tell which version they have open."""
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).strftime("%b %d, %H:%M UTC")


def write_web(uni: University, semester: int = 1) -> list[Path]:
    cfg = json.loads(CONFIG_PATH.read_text())
    SUPABASE_DIR.mkdir(exist_ok=True)
    seed = seed_sql(uni, semester)
    (SUPABASE_DIR / "seed.sql").write_text(seed)
    admin = cfg.get("first_admin")
    first = (f"-- The first account with full access (the Registrar). Add everyone else on the Settings page.\n"
             f"insert into public.staff (email, full_name, role) values ({q(admin['email'].lower())}, {q(admin.get('name', ''))}, 'registrar')\n"
             "on conflict (email) do nothing;\n") if admin else ""
    setup = "\n".join(["-- Class Scheduling: run this once in the Supabase SQL Editor (it is safe to run again).",
                       (SUPABASE_DIR / "schema.sql").read_text(), seed, first, DEFAULT_REQUESTS])
    (SUPABASE_DIR / "setup.sql").write_text(setup)

    data = json.dumps(planner_data(uni, semester), separators=(",", ":")).replace("</", "<\\/")
    backend = json.dumps({"kind": "supabase", "url": cfg["url"], "key": cfg["anon_key"]})
    html = (TEMPLATE_PATH.read_text()
            .replace("/*__DATA__*/null", data)
            .replace('/*__SEAL__*/""', json.dumps(seal_data_url()))
            .replace("/*__BACKEND__*/null", backend)
            .replace('/*__BUILD__*/""', json.dumps(build_label()))
            .replace("<!--__SUPABASE_JS__-->", f'<script src="{SUPABASE_JS}"></script>'))
    WEB_DIR.mkdir(exist_ok=True)
    (WEB_DIR / "index.html").write_text(html)
    return [WEB_DIR / "index.html", SUPABASE_DIR / "seed.sql", SUPABASE_DIR / "setup.sql"]
